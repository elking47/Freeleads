// Today: the 8 AM delivery, onboarding checklist and the day's Freeleads split by fit.
import { api } from "../../lib/api.js";
import { formatLongDate, h, icon, replace } from "../../lib/dom.js";
import { disciplineLabel, emptyState, leadCard, pageHead } from "../components.js";
import { openLead } from "../lead-drawer.js";
import { loadTemplates, state } from "../state.js";

const STRONG_FIT = 80;

async function fetchAll(query) {
  const first = await api("/leads", { query });
  const leads = [...first.leads];
  for (let page = 2; leads.length < first.total && page <= 4; page++) {
    leads.push(...(await api("/leads", { query: { ...query, page } })).leads);
  }
  return { ...first, leads };
}

function greeting(name) {
  const hour = new Date().getHours();
  const part = hour < 12 ? "Good morning" : hour < 18 ? "Good afternoon" : "Good evening";
  return `${part}, ${name.split(" ")[0]}`;
}

function deliveryCard(delivery) {
  const labels = {
    scrape: "listings scanned",
    filter: "freelance needs kept",
    enrich: "decision-makers found",
    deliver: "delivered to you",
  };
  return h("section", { class: "card", "aria-labelledby": "delivery-title" },
    h("div", { class: "card-pad" },
      h("h2", { class: "card-title", id: "delivery-title" }, "Last night's run"),
      h("p", { class: "card-sub" },
        delivery.mode === "demo"
          ? "Demo data: fictional companies and contacts, generated by the built-in demo source."
          : "Scraped, filtered and enriched between 10 PM and 8 AM.")
    ),
    h("ol", { class: "delivery", role: "list" },
      delivery.stages.map((stage) =>
        h("li", { class: "delivery-step" },
          h("p", { class: "delivery-window" }, stage.window),
          h("p", { class: "delivery-count" }, (stage.count ?? 0).toLocaleString("en")),
          h("p", { class: "delivery-label" }, labels[stage.id] ?? stage.label)
        )
      )
    )
  );
}

function checklist(user, totals, templates) {
  const items = [
    { done: user.disciplines.length > 0, text: "Choose your disciplines", minutes: 1, href: "#/settings" },
    { done: user.dailyRate !== null, text: "Set your daily rate for templates", minutes: 1, href: "#/settings" },
    { done: totals.contacted > 0, text: "Contact your first Freeleads", minutes: 3 },
    { done: totals.ratedUp + totals.ratedDown > 0, text: "Rate a lead to tune your feed", minutes: 1 },
    { done: templates.some((t) => t.mine), text: "Write your own template", minutes: 5, href: "#/templates" },
  ];
  const done = items.filter((i) => i.done).length;
  if (done === items.length) return null;

  return h("section", { class: "card card-pad", "aria-labelledby": "checklist-title" },
    h("h2", { class: "card-title", id: "checklist-title" }, "Land your first mission"),
    h("p", { class: "card-sub" }, `${done} of ${items.length} steps done`),
    h("div", { class: "progress", "aria-hidden": "true" }, h("span", { vars: { value: `${(done / items.length) * 100}%` } })),
    h("ul", { class: "checklist" },
      items.map((item) =>
        h("li", { dataset: { done: String(item.done) } },
          h("span", { class: "check-dot", "aria-hidden": "true" }, item.done ? icon("check", { size: 14 }) : null),
          h("span", { class: "check-text" },
            item.href && !item.done ? h("a", { href: item.href }, item.text) : item.text,
            h("span", { class: "visually-hidden" }, item.done ? " (done)" : " (to do)")),
          h("span", { class: "check-time" }, `${item.minutes} min`)
        )
      )
    )
  );
}

export async function render() {
  const user = state.user;
  const [delivery, feed, analytics, templates] = await Promise.all([
    api("/leads/delivery"),
    fetchAll({ view: "today", sort: "score" }),
    api("/analytics"),
    loadTemplates(),
  ]);

  const strong = feed.leads.filter((l) => l.listing.fitScore >= STRONG_FIT);
  const worth = feed.leads.filter((l) => l.listing.fitScore < STRONG_FIT);
  const disciplines = user.disciplines.map(disciplineLabel).join(", ");

  const lists = h("div");
  // The side column (checklist, plan) is re-rendered whenever a lead changes, so progress shows at once.
  const side = h("div", { class: "settings-grid" });
  const renderSide = (stats) =>
    replace(side,
      checklist(user, stats.totals, templates),
      h("section", { class: "card card-pad" },
        h("h2", { class: "card-title" }, "Your plan today"),
        h("p", { class: "card-sub" },
          `${delivery.delivered} of ${delivery.quota ?? "unlimited"} Freeleads delivered · ${user.plan.disciplines} discipline${user.plan.disciplines > 1 ? "s" : ""} included`),
        h("p", { class: "card-sub" }, `Reply rate so far: ${stats.rates.reply}% · Close rate: ${stats.rates.close}%`)));
  const refreshSide = async () => renderSide(await api("/analytics"));

  const storeLead = (updated) => {
    for (const list of [strong, worth]) {
      const index = list.findIndex((l) => l.id === updated.id);
      if (index >= 0) list[index] = updated;
    }
  };
  // A card redraws itself after a rating (and keeps keyboard focus); drawer changes redraw the lists.
  const onCardUpdated = (updated) => {
    storeLead(updated);
    refreshSide();
  };
  const onDrawerChange = (updated) => {
    storeLead(updated);
    renderLists();
    refreshSide();
  };

  function renderLists() {
    const onOpen = (id) => openLead(id, { onChange: onDrawerChange });
    const section = (title, hint, leads) =>
      leads.length
        ? [
            h("h2", { class: "section-title" }, title, h("span", { class: "badge" }, String(leads.length))),
            hint ? h("p", { class: "muted" }, hint) : null,
            h("ul", { class: "lead-list" }, leads.map((lead) => leadCard(lead, { onOpen, onUpdated: onCardUpdated }))),
          ]
        : [];
    replace(lists,
      section("Strong fits", null, strong),
      section("Worth a look", "Lower fit score, but still a real freelance need.", worth));
  }
  renderLists();
  renderSide(analytics);

  const subtitle = feed.deliveredOn
    ? `${formatLongDate(feed.deliveredOn)} · ${feed.total} new Freeleads in ${disciplines}`
    : `Your first Freeleads arrive at 8 AM in ${disciplines}.`;

  return h("div", {},
    pageHead(greeting(user.name), subtitle,
      h("a", { class: "btn", href: "#/pipeline" }, icon("kanban"), "Open pipeline")),

    user.plan.trialExpired
      ? h("div", { class: "banner", role: "status" },
          h("span", {}, h("strong", {}, "Your trial has ended. "), "Choose a plan to keep receiving Freeleads every morning."),
          h("a", { class: "btn btn-sm btn-primary", href: "#/settings" }, "Choose a plan"))
      : null,

    h("div", { class: "today-grid" },
      h("div", {},
        delivery.stages.length ? deliveryCard(delivery) : null,
        feed.leads.length
          ? lists
          : emptyState("No Freeleads yet today", "Your next delivery arrives at 8 AM. Meanwhile, work your pipeline.",
              h("a", { class: "btn", href: "#/leads" }, "See all leads"))
      ),
      side
    )
  );
}
